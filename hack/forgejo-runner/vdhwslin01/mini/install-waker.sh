#!/usr/bin/env bash
# Installs the vdhwslin01 waker on vdhmini01 from a commit ON origin/main to a fixed
# path outside any checkout (Argus B4, chg-2026-10-05-031). Never from a working tree.
#
#   install-waker.sh <commit> [--load]
#
# - fetches origin, refuses unless <commit> is an ancestor of origin/main;
# - writes the waker exactly as stored at <commit> (git show, not the working tree)
#   to ~/.local/libexec/vdhwslin01-waker/vdhwslin01-waker.py, mode 0555;
# - pins its sha256, the absolute kubectl and the absolute change log into the
#   launchd plist (ProgramArguments), so the waker self-checks at every start;
# - records commit + sha in ~/.local/libexec/vdhwslin01-waker/INSTALLED (0444);
# - --load: launchctl bootstrap (only after Argus + Hestia's webhook + C8). Without
#   it nothing is loaded.
# Rollback: launchctl bootout gui/$(id -u)/net.vdhict.vdhwslin01-waker; move the
# plist out of ~/Library/LaunchAgents to ~/Library/LaunchAgents.retired/.
# Paths can be redirected for tests: WAKER_HOME (default $HOME), REPO.
set -euo pipefail
commit="${1:?commit on origin/main}"; load=0; [[ "${2:-}" == --load ]] && load=1
REPO="${REPO:-/Users/sheijden/Code/homelab-migration/vdhinfra}"
H="${WAKER_HOME:-$HOME}"
DEST="$H/.local/libexec/vdhwslin01-waker"
# The plist is generated NEXT TO the waker; it goes into ~/Library/LaunchAgents only with --load,
# because launchd loads every plist in that folder at the next login (no accidental go-live).
PL="$DEST/net.vdhict.vdhwslin01-waker.plist"; LA="$H/Library/LaunchAgents/net.vdhict.vdhwslin01-waker.plist"
SRC=hack/forgejo-runner/vdhwslin01/mini/vdhwslin01-waker.py
KUBECTL="${KUBECTL:-$(command -v kubectl || true)}"
CHANGES="$REPO/ops/changes.jsonl"
die() { echo "install-waker: $*" >&2; exit 2; }

[[ "$KUBECTL" == /* && -x "$KUBECTL" ]] || die "kubectl must resolve to an absolute executable (set KUBECTL=/abs/path)"
[[ -f "$CHANGES" ]] || die "$CHANGES missing"
git -C "$REPO" fetch -q origin main
full="$(git -C "$REPO" rev-parse --verify "${commit}^{commit}")" || die "unknown commit $commit"
git -C "$REPO" merge-base --is-ancestor "$full" origin/main || die "$full is not on origin/main; refusing"

umask 022
mkdir -p "$DEST"
tmp="$DEST/.vdhwslin01-waker.py.new"
git -C "$REPO" show "${full}:${SRC}" > "$tmp"
chmod 0555 "$tmp"; mv -f "$tmp" "$DEST/vdhwslin01-waker.py"
sha="$(shasum -a 256 "$DEST/vdhwslin01-waker.py" | cut -d' ' -f1)"
[[ "$sha" == "$(git -C "$REPO" show "${full}:${SRC}" | shasum -a 256 | cut -d' ' -f1)" ]] || die "installed copy differs from $full"

cat > "$PL.new" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- chg-2026-10-05-031 vdhwslin01 waker; generated by install-waker.sh from ${full} -->
<plist version="1.0">
<dict>
  <key>Label</key><string>net.vdhict.vdhwslin01-waker</string>
  <key>ProgramArguments</key><array>
    <string>/usr/bin/python3</string><string>-I</string>
    <string>${DEST}/vdhwslin01-waker.py</string>
    <string>--expect-sha256</string><string>${sha}</string>
    <string>--kubectl</string><string>${KUBECTL}</string>
    <string>--changes-log</string><string>${CHANGES}</string>
  </array>
  <key>StartInterval</key><integer>120</integer>
  <key>RunAtLoad</key><false/>
  <key>ProcessType</key><string>Background</string>
  <key>StandardOutPath</key><string>${H}/Library/Logs/vdhwslin01-waker.log</string>
  <key>StandardErrorPath</key><string>${H}/Library/Logs/vdhwslin01-waker.log</string>
</dict>
</plist>
EOF
plutil -lint "$PL.new" >/dev/null
mv -f "$PL.new" "$PL"
[[ ! -e "$DEST/INSTALLED" ]] || chmod 0644 "$DEST/INSTALLED"
printf 'commit=%s\nsha256=%s\nkubectl=%s\nchanges_log=%s\ninstalled_utc=%s\n' "$full" "$sha" "$KUBECTL" "$CHANGES" "$(date -u +%FT%TZ)" > "$DEST/INSTALLED"
chmod 0444 "$DEST/INSTALLED"
echo "installed $DEST/vdhwslin01-waker.py sha256 $sha from $full; plist $PL (not in LaunchAgents, not loaded)"
if (( load )); then
  mkdir -p "$(dirname "$LA")"; cp -f "$PL" "$LA"
  launchctl bootstrap "gui/$(id -u)" "$LA"
  launchctl print "gui/$(id -u)/net.vdhict.vdhwslin01-waker" | grep -E 'state|run interval' || true
fi
